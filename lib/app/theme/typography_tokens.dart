// 语义化排版令牌 —— 全仓字号的**唯一出口**。
//
// ─────────────────────────────────────────────────────────────────────────
// 为什么要有这个文件
//
// 迁移前 `lib/` 里有 **451 处 `fontSize:` 字面量、26 个不同取值**，且同一个值
// 常同时承担多种语义（`13` 既是分组标题、又是表单标签、还是说明文字）。后果：
//   ① 各页天然参差（设置项 15.8 / 记忆卡片标题 18.5 / 技能列表 15 / 诊断 14）；
//   ② 想按语义统一调整时无处下手（改 13 会同时动到三类东西）；
//   ③ 宽窄分流只做了一半（仅聊天正文有 `markdownBodyFontSizeFor`）。
//
// ─────────────────────────────────────────────────────────────────────────
// 取值依据：以**左壳侧栏的既有值**为视觉锚
//
// 左壳侧栏（`app/shell/session_sidebar.dart` 一族）是用户注视最多的区域，它的
// 既有取值就是「视觉基准」，右侧内容锚到它，「左右不相符」便从根上消失：
//   导航项 15.0 · 会话标题 14 · 会话副标题 12.5 · 状态栏 11.5
//
// ─────────────────────────────────────────────────────────────────────────
// 使用规则（迁移/审计时每一处都照这个自问）
//
//   这一行的**东西**是「一个名字」「一句话」「一句注解」「一个字段名」还是「一个数字」？
//
//   · 是某个**区块/分组的名字**（「外观」「置顶」「今天」）…… `kFontSectionTitle`
//   · 是某个**东西的名字**（技能名、设置项名、卡片标题、任务名）…… `kFontItemTitle`
//   · 是**成句的内容**（描述、正文、说明段）………………………… `kFontBody`
//   · 是**长文阅读内容**（聊天正文、记忆正文 —— 需要更舒适的行内字号）… `kFontReadingBody`
//   · 是**表单字段名**（服务器名称 / 地址 / 密码）…………………… `kFontLabel`
//   · 是**注解**（说明文字、副标题、时间戳、路径）……………………… `kFontCaption`
//   · 是**角标/计数**（徽标数字、条目计数）…………………………… `kFontMicro`
//   · 是**等宽内容**（代码、diff、日志）………………………………… `kFontCode`
//
//   ⚠️ 最常见的三种错用（审计重点）：
//     (a) 用 `kFontItemTitle`(15) 写**说明文字** ⇒ 注解抢了名字的戏；
//     (b) 用 `kFontBody`(14) 写**东西的名字** ⇒ 名字不突出，与正文糊在一起；
//     (c) 用 `kFontCaption`(12) 写**表单字段名** ⇒ 字段名太弱，标签像注解。
//
// ─────────────────────────────────────────────────────────────────────────
// 与「宽度分流」「HiDPI」的关系
//
// · HiDPI（界面缩放）**不在这里处理** —— 它在最外层用 `MediaQuery` 覆写统一缩放
//   （见 `ui_scale_provider.dart` 的 `applyUiScale`），字号令牌不必知情。
// · 宽窄分流目前只对**长文阅读**成立（聊天/记忆正文宽屏缩一档，见
//   `chat/widgets/markdown_styles.dart` 的 `markdownBodyFontSizeFor`）。若日后要把
//   「宽屏缩一档」推广到别的语义档，请照同一模式加 `kFontXxxFor(context)`，
//   而**不要**在调用点重新写 `isWide ? a : b`。
//
// 注意：本文件只放**常量与判据**，不引入依赖（避免 `theme` 与 `features` 成环）。
// ─────────────────────────────────────────────────────────────────────────

/// 页面导航栏标题（系统档）。值 17。
///
/// 消费方：各页 `CupertinoNavigationBar` 的标题；`CupertinoListTile` 默认标题也
/// 落在这个量级（历史原因它没写字号，迁移时**保持不动**以免改动系统观感）。
const double kFontPageTitle = 17.0;

/// iOS 大标题（系统档）。值 34。
///
/// 消费方：`large_title_sliver_header.dart` 一族（滚动时收拢成导航栏标题）。
const double kFontLargeTitle = 34.0;

/// 分组小标题 —— **区块/分组的名字**。值 13。
///
/// 消费方：设置页的「外观 / 对话 / 服务」、会话列表的「置顶 / 今天 / 昨天 / 更早」、
/// 技能页的「协作与治理 / 文档与交付」。
const double kFontSectionTitle = 13.0;

/// 列表项名 / 卡片标题 —— **一个东西的名字**。值 15（＝左壳侧栏导航项）。
///
/// 消费方：技能名、设置项名、看板卡片标题、任务名、下载项文件名。
const double kFontItemTitle = 15.0;

/// 正文 / 描述 —— **成句的内容**。值 14（＝左壳侧栏会话标题）。
///
/// 消费方：列表项下面的描述行、设置项说明段、详情面板正文。
const double kFontBody = 14.0;

/// 长文阅读正文 —— 需要更舒适行内字号的**成篇内容**。值 15；宽屏 13.5。
///
/// 消费方：聊天正文、记忆正文（二者同源，走
/// `chat/widgets/markdown_styles.dart` 的 `markdownBodyFontSizeFor`）。
/// 之所以比 [kFontBody] 大一档：成篇阅读与「列表里的一行描述」的舒适度不同，
/// 这是既有设计（2026-09-27 P6 确认），**不要**在本文件里把它合并掉。
const double kFontReadingBody = 15.0;

/// 表单字段名 / 次要正文。值 13。
///
/// 消费方：「服务器名称 / 地址 / 密码」这类输入框上方的标签、次要段落。
const double kFontLabel = 13.0;

/// 注解 —— 说明文字 / 副标题 / 时间戳 / 路径。值 12。
///
/// 消费方：设置项的说明行（「整体缩放界面；档位越高越可能转为单栏」）、会话副标题、
/// 相对时间、文件路径。
const double kFontCaption = 12.0;

/// 角标 / 计数 —— 徽标数字、条目计数。值 11。
///
/// 消费方：会话列表分组计数、技能标签计数、底栏状态栏。
const double kFontMicro = 11.0;

/// 等宽内容 —— 代码 / diff / 日志。值 12。
///
/// 消费方：Git 变更面板的 diff、工作区代码预览、诊断日志。
/// 之所以单列一档：等宽字体的 x-height 与比例字体不同，同值观感偏大，
/// 且这类内容以「扫读结构」为主，紧凑优先。
const double kFontCode = 12.0;
/// 按钮文字。值 13。
///
/// 与 [kFontLabel] **同值但异义** —— 审计时不要因为数值相同就互换：
/// 「字段名」与「动作」是两种东西，日后若要把按钮整体调大，改这里即可，
/// 而不该连带把表单标签一起改了。
const double kFontButton = 13.0;

/// 兜底默认 —— `settings_surfaces.dart` 的 `DefaultTextStyle` 用值。值 13。
///
/// **新代码不要用**。它的存在只是承认现状：继承方未显式给语义时，13 是历史
/// 默认值（全仓 119 处 `13` 里多数由它兜底而来）。迁移的目标是让每一处都写明
/// 自己的语义（itemTitle / body / label / caption…），而不是继续靠继承。
const double kFontDefault = 13.0;
/// 页面内导航文字（二级导航）—— 分段控件 tab、宽屏左栏导航行。值 13。
///
/// 层级关系：**一级导航**（壳侧栏的「新建会话/看板/技能」）用 [kFontItemTitle] 15，
/// **二级导航**（页面内部的分类/分段）用本档 13 —— 视觉上「外层重、内层轻」。
///
/// 迁移前的乱用：同一件事出现了三个值（壳侧栏 15 / 记忆页 tab 13 /
/// `wide_nav_rail` 12.5）。12.5 这个值原本是壳侧栏**副标题**的，被借到这里
/// 属于错用，故一并收进本档。
const double kFontNavItem = 13.0;
/// 侧栏项名（窄栏里的「东西的名字」）。值 14。
///
/// 与 [kFontItemTitle](15) **同类但不同容器**：壳侧栏只有 320pt 宽，会话标题
/// 用 15 会显得挤，14 是既有事实值（也是本梯子的视觉锚之一）。
/// 迁移时若发现「内容区」的项名误用了本档，那才是错用 —— 判断依据是**容器**：
/// 侧栏/栏内导航用本档，内容区用 [kFontItemTitle]。
const double kFontSidebarTitle = 14.0;

/// ⚠️ 尚未进梯子的唯一事实值：**12.5**（会话行副标题）。
///
/// 它是**壳侧栏副标题的基准值**，属视觉锚，**刻意保留**（不并入 kFontCaption 12）。
/// 其余历史零散值（`10.5` / `10`）已按主人 2026-09-28 的拍板统一到 [kFontMicro] 11。
// ─────────────────────────────────────────────────────────────────────────
// 侧栏专档（壳侧栏 / 悬停提示 / 状态栏）
//
// 为什么单独一组：侧栏的值是**主人逐轮实测调过**的（代码注释留有记录 —— 
// 「#161：回到设计稿口径（12.5）」「#153 曾统一抬到 15，主人实测侧栏比设计稿
// 大一圈，此处回调」「抬到 15…此处回调」）。它**不是**内容区梯子的子集，
// 而是一套独立的设计稿口径。
//
// 因此这里**逐个固定为具名令牌**：值一律不变（零视觉变化），只是把「散在各文件
// 里的同一个数字」变成「同一个名字」，日后要调侧栏时一处改全部生效。
// ─────────────────────────────────────────────────────────────────────────

/// 侧栏元信息（会话副标题 / 工具行标签）。值 12.5。
///
/// 这也是整个梯子里**唯一刻意不并入内容区档位**的值：它被主人实测确认过
/// （#161 回到设计稿口径），并入 kFontCaption(12) 会改观感。
const double kFontSidebarMeta = 12.5;

/// 侧栏二级副标题（品牌区下方的小字）。值 10（设计稿 .brand .sub2 = 10）。
const double kFontSidebarSub = 10.0;

/// 侧栏徽标 / 计数（工具行右侧角标）。值 10.5（#161 随侧栏整体回调）。
const double kFontSidebarBadge = 10.5;

/// 侧栏状态行 / 悬停提示。值 11.5。
const double kFontSidebarStatus = 11.5;